TEST(Number, ModPow) {
  number p = number::parse_hex(kBigPrime);
  number e = "10001"_number;
  number phi = p - number::one();
  number inv_e_phi;
  std::tie(inv_e_phi, std::ignore, std::ignore) = number::gcd(e, phi);
  number r = number::parse_hex(kBigNumber);
  number r0 = r;
  r.pow_mod(e, p);
  EXPECT_NE(r0, r);
  r.pow_mod(inv_e_phi, p);
  EXPECT_EQ(r0, r);
}

